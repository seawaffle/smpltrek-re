#!/usr/bin/env python3
"""Cross-reference the named symbols of the three Sonicware products that share this hardware.

Reads the hand-written source symbol file (SmplTrek 3.2.174) and the files carry_symbols.py generated for
the other products, groups every symbol into a subsystem, and writes a Markdown table showing where each
one lives in every product and how well its body matched. A symbol missing from a product means
func_match found no counterpart: either the code is absent there or it was compiled too differently to
match. The table cannot tell which; docs/01-platform-map.md records what was checked by hand.

Usage (from the repository root):
  python3 -B analysis/platform_map.py [-o docs/02-platform-symbols.md]
"""
import argparse
import collections
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
SOURCE = ROOT / "symbols/smpltrek-3.2.174.json"
PRODUCTS = [  # (column title, carried symbol file)
    ("Lofi-12 XT 1.5.205", ROOT / "symbols/lofi-12xt-1.5.205.json"),
    ("CyDrums 1.1.84", ROOT / "symbols/cydrums-1.1.84.json"),
]

# First matching rule wins. Order matters: specific patterns before broad ones.
SUBSYSTEMS = [
    ("TI StarterWare McASP / EDMA3 drivers", r"^(McASP|EDMA3)|^g_edma3"),
    ("Audio: codec and McASP setup", r"codec|mcasp_|audio_start_transfers|audio_clock_probe"),
    ("Audio: block processing and mix", r"^audio_|^g_audio_|_effects|^SoundEffect::|^Swi_"),
    ("Tracks", r"^TrackSound::|tracks|_track"),
    ("FatFs and SD", r"^(f_|disk_)"),
    ("SPI flash", r"[Ff]lash|^g_spi"),
    ("MIDI", r"[Mm][Ii][Dd][Ii]"),
    ("Pads and panel controller", r"pad|ADController|ad_controller"),
    ("Buttons", r"control_switch|AppTestControl"),
    ("Settings", r"setting"),
    ("Display and text", r"draw|font|title"),
    ("SYS/BIOS and run-time", r"^(Event_|Mailbox|Cache_|cache_|mailbox_|Task_|Hwi_|Semaphore_)"),
    ("Application framework", r"MainDelegate|app_|message"),
]
SIMILARITY = re.compile(r"body similarity ([0-9.]+)")


def subsystem(name):
    for title, pattern in SUBSYSTEMS:
        if re.search(pattern, name):
            return title
    return "Other"


def load(path):
    return {s["name"]: s for s in json.loads(Path(path).read_text())["symbols"]}


def similarity(entry):
    """Body similarity recorded by carry_symbols.py for a function, or None for data symbols."""
    for line in entry.get("evidence", []):
        m = SIMILARITY.search(line)
        if m:
            return float(m.group(1))
    return None


def cell(entry):
    if entry is None:
        return "—"
    s = similarity(entry)
    text = f"`{int(entry['address'], 16):#010x}`"
    return text if s is None or s >= 1.0 else f"{text} ({s:.2f})"


def build(source, products):
    """Return {subsystem: [(name, kind, source address, [target entry or None per product])]}."""
    rows = collections.defaultdict(list)
    for name, entry in sorted(source.items(), key=lambda kv: int(kv[1]["address"], 16)):
        rows[subsystem(name)].append((name, entry["kind"], entry["address"], [p.get(name) for p in products]))
    return rows


def render(rows, titles):
    order = [t for t, _ in SUBSYSTEMS] + ["Other"]
    out = ["# Platform symbol cross-reference", "",
           "Generated by `analysis/platform_map.py` from `symbols/`; do not edit by hand. "
           "Addresses per product; a number in brackets is the normalised body similarity when below 1.0; "
           "— means func_match found no counterpart (absent, or compiled too differently to match). "
           "What was checked by hand is in `01-platform-map.md`.", "",
           "## Summary", "",
           "| Subsystem | Named in SmplTrek | " + " | ".join(f"In {t}" for t in titles) + " | In all three |",
           "|---|---|" + "---|" * len(titles) + "---|"]
    for title in order:
        if title not in rows:
            continue
        r = rows[title]
        per = [sum(1 for x in r if x[3][i] is not None) for i in range(len(titles))]
        both = sum(1 for x in r if all(t is not None for t in x[3]))
        out.append(f"| {title} | {len(r)} | " + " | ".join(map(str, per)) + f" | {both} |")
    for title in order:
        if title not in rows:
            continue
        out += ["", f"## {title}", "",
                "| Symbol | Kind | SmplTrek 3.2.174 | " + " | ".join(titles) + " |",
                "|---|---|---|" + "---|" * len(titles)]
        for name, kind, address, targets in rows[title]:
            out.append(f"| `{name}` | {kind} | `{int(address, 16):#010x}` | " + " | ".join(cell(t) for t in targets) + " |")
    return "\n".join(out) + "\n"


MATCHES = [ROOT / "work/match-3.2.174-Lofi-12XT_v1.5.205.json",
           ROOT / "work/match-3.2.174-CyDrums_v1.1.84.json"]  # same order as PRODUCTS


def area(address, names, owners):
    """Label for one SmplTrek function: our subsystem when named, else the RTTI namespace of the class
    owning it as a virtual function, else unlabelled."""
    if address in names:
        return "named: " + subsystem(names[address])
    owner = owners.get(address)
    if owner:
        return owner.split("::")[0] + "::" if "::" in owner else "app classes (no namespace)"
    return "unlabelled"


def area_stats(starts, end, names, owners, matched):
    """{label: [functions, bytes, functions in all, bytes in all]}; matched = per-product sets of
    SmplTrek function addresses."""
    stats = collections.defaultdict(lambda: [0, 0, 0, 0])
    for i, a in enumerate(starts):
        size = (starts[i + 1] if i + 1 < len(starts) else end) - a
        r = stats[area(a, names, owners)]
        r[0] += 1
        r[1] += size
        if all(a in m for m in matched):
            r[2] += 1
            r[3] += size
    return stats


def runs(pairs, min_functions=3):
    """Maximal runs of consecutive matched functions with one address delta: identically laid-out code.
    pairs: sorted (a, b). Returns [(first a, last a, delta, count)]."""
    out, cur = [], None
    for a, b in pairs:
        if cur and b - a == cur[2]:
            cur = (cur[0], a, cur[2], cur[3] + 1)
        else:
            if cur:
                out.append(cur)
            cur = (a, a, b - a, 1)
    if cur:
        out.append(cur)
    return [r for r in out if r[3] >= min_functions]


def common_blocks(per_product_pairs, min_bytes=0x40):
    """Ranges of SmplTrek code laid out identically in every product: [(start, end, [delta per product])].
    end is the last matched function start in the range (its body is not included)."""
    blocks = [(s, e, [d]) for s, e, d, _ in runs(per_product_pairs[0])]
    for pairs in per_product_pairs[1:]:
        nxt = []
        for s, e, ds in blocks:
            for s2, e2, d2, _ in runs(pairs):
                lo, hi = max(s, s2), min(e, e2)
                if hi - lo >= min_bytes:
                    nxt.append((lo, hi, ds + [d2]))
        blocks = nxt
    return sorted(blocks)


def block_label(start, end, names, owners):
    inside = [names[a] for a in names if start <= a <= end]
    if inside:
        return ", ".join(sorted({subsystem(n) for n in inside}))
    spaces = collections.Counter(area(a, {}, owners) for a in owners if start <= a <= end)
    return ", ".join(f"{k}" for k, _ in spaces.most_common(3)) or "unlabelled"


def render_shared(stats, blocks, diffs, titles):
    out = ["# Platform shared-code map", "",
           "Generated by `analysis/platform_map.py --shared`; do not edit by hand. Lower bounds: a "
           "function counts as shared only when func_match paired it in every other product (" +
           ", ".join(titles) + "); conservative matching misses some genuinely shared code.", "",
           "## Shared functions by area", "",
           "Area = our subsystem when the function is named, else the RTTI namespace of the class that owns "
           "it as a virtual function, else unlabelled.", "",
           "| Area | Functions | Bytes | Shared by all | Shared bytes | Share |", "|---|---|---|---|---|---|"]
    for k, (n, b, sn, sb) in sorted(stats.items(), key=lambda kv: -kv[1][1]):
        out.append(f"| {k} | {n} | {b} | {sn} | {sb} | {100 * sb / b:.0f}% |")
    t = [sum(v[i] for v in stats.values()) for i in range(4)]
    out.append(f"| **total** | {t[0]} | {t[1]} | {t[2]} | {t[3]} | {100 * t[3] / t[1]:.0f}% |")
    out += ["", "## Identically laid-out blocks", "",
            "Runs of at least 3 consecutive matched functions with one address delta in every product. Each "
            "block was disassembled in all three and compared with constants kept (`region_diff.py`): "
            "*addr* = moved data-address halves, *dp* = different B14 data-page offsets (both are layout, not "
            "behaviour), *other* = real differences in code or constants. Ranges end at the last matched "
            "function start.", "",
            "| SmplTrek range | Bytes | Label | " + " | ".join(f"{t} delta, addr/dp/other" for t in titles) + " |",
            "|---|---|---|" + "---|" * len(titles)]
    for (s, e, ds), (label, per) in zip(blocks, diffs):
        cells = [f"{d:+#x}, {c['address']}/{c['b14']}/{c['other']}" for d, c in zip(ds, per)]
        out.append(f"| `{s:#010x}`-`{e:#010x}` | {e - s} | {label} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def shared(output):
    import func_match
    import region_diff
    program = func_match.load(ROOT / "firmware/smpltrek/SmplTrek v3.2.174.zip")
    lo, hi = program.image.code
    owners = {}
    for c in program.rtti["classes"]:
        for vt in c["vtables"]:
            for e in vt["entries"]:
                if e and lo <= int(e, 16) < hi:
                    owners.setdefault(int(e, 16), c["name"])
    names = {int(s["address"], 16): n for n, s in load(SOURCE).items() if s["kind"] == "function"}
    pairs = [sorted((int(m["a"], 16), int(m["b"], 16)) for m in json.loads(p.read_text())["matches"])
             for p in MATCHES]
    stats = area_stats(program.starts, hi, names, owners, [{a for a, _ in ps} for ps in pairs])
    blocks = common_blocks(pairs)
    diffs = []
    for s, e, ds in blocks:
        base = region_diff.disassemble(region_diff.SOURCE_ELF, s, e - s)
        per = [region_diff.compare(base, region_diff.disassemble(elf, s + d, e - s))[0]
               for (_, elf, _), d in zip(region_diff.PRODUCTS, ds)]
        diffs.append((block_label(s, e, names, owners), per))
    Path(output).write_text(render_shared(stats, blocks, diffs, [t for t, _ in PRODUCTS]))
    print(f"Wrote {output}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output", default=str(ROOT / "docs/02-platform-symbols.md"))
    ap.add_argument("--shared", nargs="?", const=str(ROOT / "docs/03-platform-shared.md"),
                    help="instead write the shared-code map (needs firmware/, work ELFs and match files)")
    args = ap.parse_args()
    if args.shared:
        shared(args.shared)
        return 0
    titles = [t for t, _ in PRODUCTS]
    text = render(build(load(SOURCE), [load(p) for _, p in PRODUCTS]), titles)
    Path(args.output).write_text(text)
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
